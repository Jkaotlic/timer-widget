const { defineConfig } = require('@playwright/test');

module.exports = defineConfig({
    testDir: './e2e',
    // Сносит и создаёт заново каталог профиля (см. e2e/global-setup.js): тесты
    // делят один профиль внутри прогона, но не должны наследовать предыдущий.
    globalSetup: require.resolve('./e2e/global-setup.js'),
    /**
     * Бюджет теста — 120 с, и это НЕ запас «на всякий случай».
     *
     * Каждый тест здесь поднимает НАСТОЯЩЕЕ приложение Electron, открывает
     * окна и ждёт настоящих переходов (полноэкранный режим, анимации створок,
     * подгонка кегля). Локально самый долгий занимает 18.7 с — при умолчании
     * Playwright в 30 с запас был меньше двух раз, а macOS-раннер прогоняет
     * всю сюиту за 25 минут против локальных десяти.
     *
     * 09.09.2026 это перестало быть теорией: в релизе 2.8.0 три прогона CI
     * подряд падали на macOS, и первый — по этой самой причине. Лечили тогда
     * поштучно: 61 тест из 241 успел обзавестись собственным `test.setTimeout`,
     * причём 38 из них — ровно на 120000. То есть проект уже выбрал это число
     * голосованием, просто держал его в 38 копиях вместо одного места.
     *
     * Величина одна и владелец у неё один — здесь. Свой `test.setTimeout`
     * остаётся законным только чтобы ПОДНЯТЬ бюджет отдельному тяжёлому тесту
     * (в наборе такие есть: 150–240 с); опустить его ниже умолчания нельзя —
     * это ослабление, которого никто не заметит, и его ловит
     * tests/e2e-budget.test.js.
     *
     * На зелёный прогон число не влияет вовсе: бюджет тратится только тем,
     * кто уже завис.
     */
    timeout: 120000,
    retries: 0,
    // ОДИН воркер обязателен: приложение держит single-instance lock
    // (app.requestSingleInstanceLock в electron-main.js), поэтому второй
    // параллельно запущенный экземпляр немедленно завершается, и тесты во
    // втором файле падают с «Process failed to launch». Последовательный прогон —
    // не оптимизация, а требование архитектуры приложения.
    workers: 1,
    fullyParallel: false,
    use: {
        trace: 'on-first-retry',
    },
});
