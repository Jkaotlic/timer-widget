'use strict';

/**
 * main-state.js — общее изменяемое состояние главного процесса. ОДИН владелец.
 *
 * До 25.09.2026 главный процесс был одним файлом, и эти величины были его
 * переменными верхнего уровня (`let controlWindow = null` и соседи). После
 * разбиения на модули у каждой из них должен остаться один хозяин: копия
 * ссылки на окно в модуле — это вторая правда, которая разойдётся с первой в
 * тот момент, когда окно закроют. Поэтому точка входа создаёт эти объекты
 * ОДИН раз и передаёт их модулям, а модули читают и пишут поля объекта — не
 * держат своих копий.
 *
 * Имена полей — прежние имена переменных, намеренно: «Window references are
 * global (`controlWindow`, …)» в CLAUDE.md, разборы в docs/lessons.md и
 * source-level тесты говорят этими именами.
 *
 * Объекты запечатаны (Object.seal): опечатка в имени поля при записи бросает
 * в строгом режиме, а не заводит тихо пятое «окно», которое никто не читает.
 *
 * Модуль чистый — ни electron, ни файлов.
 */

/**
 * Четыре окна приложения. `null` — окна нет (или событие `closed` уже
 * пришло). Закрывающееся, но ещё не закрытое окно отличает
 * main-window-closing.js, а не этот объект.
 */
function createWindowRegistry() {
    return Object.seal({
        controlWindow: null,
        widgetWindow: null,
        displayWindow: null,
        clockWidgetWindow: null
    });
}

/**
 * Что главный процесс ПОМНИТ из каналов-ретрансляторов, чтобы дослать окну,
 * открытому позже (правило «снимок при загрузке, а не только рассылка»).
 */
function createRelayMemory() {
    return Object.seal({
        // Сохраняем последние настройки дисплея для синхронизации
        lastDisplaySettings: null,
        lastDisplayIndex: 'auto',
        // Per-window colors (independent themes)
        lastWidgetColors: null,
        lastClockColors: null,
        lastDisplayColors: null,
        lastWidgetStyle: null,
        /**
         * Настройки окна часов (дата, пояс, секунды, 24 ч, цифры циферблата).
         *
         * Главный процесс их ПОМНИТ, а не только ретранслирует: окно, открытое после
         * того как панель прислала настройки, иначе узнавало бы о них только потому,
         * что читает тот же localStorage. Там, где эта подпорка не работает — гонка
         * старта в режиме съёмки, когда окна успевают прочитать хранилище раньше, чем
         * панель туда пишет, — снимок и нужен.
         */
        lastClockSettings: null
    });
}

/**
 * Флаги жизненного цикла приложения.
 *
 * `isQuitting` читают четверо: снимок восстановления (на выходе не пишется),
 * его периодическая запись, трей («закрытие панели = скрытие», пока не выход)
 * и before-quit. Ставится ДО первого чтения — при выходе из трея и в
 * before-quit.
 */
function createAppFlags() {
    return Object.seal({ isQuitting: false });
}

module.exports = { createWindowRegistry, createRelayMemory, createAppFlags };
