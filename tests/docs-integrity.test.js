'use strict';

/**
 * Связность CLAUDE.md ↔ docs/lessons.md.
 *
 * 11.08.2026 раздел Gotchas разделён надвое: в CLAUDE.md остался ИМПЕРАТИВ (одна
 * строка на правило), полный разбор уехал в docs/lessons.md. Причина — размер:
 * CLAUDE.md весил 86 КБ, из них 60 КБ (69%) занимала хроника уже починенного и
 * закреплённого тестами. Она ценна, но нужна В МОМЕНТ работы над конкретной
 * подсистемой, а не в каждом разговоре с первого слова; действующие правила в
 * ней тонули.
 *
 * Ссылка между двумя файлами — это ровно такой же реестр, как CONFIG.STORAGE_KEYS,
 * и гниёт он ровно так же и так же молча: правило переименовали — ссылка ведёт в
 * никуда; разбор удалили — правило осталось без обоснования; разбор дописали, а
 * правило забыли — его никто не прочитает. Поэтому проверяется В ОБЕ СТОРОНЫ.
 */

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const repoRoot = path.join(__dirname, '..');
const claude = fs.readFileSync(path.join(repoRoot, 'CLAUDE.md'), 'utf8');
const lessons = fs.readFileSync(path.join(repoRoot, 'docs', 'lessons.md'), 'utf8');

// Якоря в разборе объявлены явным <a id="…">, а не выведены из заголовка:
// заголовки здесь на двух языках и с кавычками-ёлочками, и правила
// автогенерации якорей у разных рендереров расходятся.
const anchors = new Set([...lessons.matchAll(/<a id="([^"]+)"><\/a>/g)].map((m) => m[1]));
const links = [...claude.matchAll(/\(docs\/lessons\.md#([^)]+)\)/g)].map((m) => m[1]);

test('каждая ссылка из CLAUDE.md ведёт в существующий разбор', () => {
    const broken = links.filter((a) => !anchors.has(a));
    assert.deepStrictEqual(
        broken, [],
        `ссылки в никуда: ${broken.join(', ')}`
    );
});

test('каждый разбор либо достижим из CLAUDE.md, либо помечен устаревшим', () => {
    // Разбор, на который никто не ссылается, — это правило, которое перестало
    // быть правилом. Молча осиротеть оно не должно.
    //
    // Но есть законный третий случай: механизм удалён, правило больше не
    // действует, а разбор ценен как объяснение ПОЧЕМУ так нельзя. Такие помечены
    // «**УСТАРЕЛО» прямо в тексте и ссылки из CLAUDE.md не имеют намеренно —
    // иначе действующие правила разбавлялись бы недействующими, ради чего файл
    // и разделили. Метка обязана быть явной: «просто нет ссылки» и «устарело
    // осознанно» со стороны выглядят одинаково.
    const sections = lessons.split(/(?=<a id=")/);
    const orphans = [];
    for (const anchor of anchors) {
        if (links.includes(anchor)) { continue; }
        const section = sections.find((s) => s.startsWith(`<a id="${anchor}">`)) || '';
        if (!section.includes('**УСТАРЕЛО')) { orphans.push(anchor); }
    }
    assert.deepStrictEqual(
        orphans, [],
        `разборы без ссылки и без пометки об устаревании: ${orphans.join(', ')}`
    );
});

test('устаревший разбор объясняет, чем его заменили', () => {
    // Пометка «устарело» без указания действующего правила оставляет читателя
    // ровно там же, где он был: он знает, что этому верить нельзя, и не знает,
    // чему верить.
    const sections = lessons.split(/(?=<a id=")/).filter((s) => s.includes('**УСТАРЕЛО'));
    assert.ok(sections.length, 'ни одного устаревшего разбора — регулярка разошлась с текстом');
    const noPointer = sections
        .filter((s) => !/\(#[a-z0-9-]+\)/.test(s.slice(s.indexOf('**УСТАРЕЛО'))))
        .map((s) => (s.match(/<a id="([^"]+)"/) || [])[1]);
    assert.deepStrictEqual(
        noPointer, [],
        `помечены устаревшими, но не сказано, что теперь верно: ${noPointer.join(', ')}`
    );
});

test('якоря разбора уникальны', () => {
    const all = [...lessons.matchAll(/<a id="([^"]+)"><\/a>/g)].map((m) => m[1]);
    const dupes = all.filter((a, i) => all.indexOf(a) !== i);
    assert.deepStrictEqual(dupes, [], `повторяющиеся якоря: ${dupes.join(', ')}`);
});

test('CLAUDE.md остался в размере, который не жалко читать целиком', () => {
    // Порог не эстетический. Этот файл целиком попадает в контекст КАЖДОГО
    // разговора ещё до того, как прочитан хоть один исходник. 86 КБ — это
    // примерно 30 тысяч токенов на старте, потраченных на хронику.
    // Порог с запасом к текущему размеру: он должен ловить возврат хроники,
    // а не каждую добавленную строку правила.
    //
    // Поднят с 55000 до 56600 13.08.2026 — и цена записана честно. Прибавка
    // (+1.5 КБ) это: строка модуля `panel-colors.js`, две строки в таблицах
    // тестов, упоминание `surfacePaint` и ОДНО правило в Gotchas со ссылкой на
    // разбор. Всё это — реестр и императив, то есть ровно то, что здесь и
    // должно жить; сам разбор фона окон (7 КБ) ушёл в docs/lessons.md.
    //
    // Поднят с 56600 до 57600 24.08.2026, и сначала было сделано то, что
    // предписывала прошлая запись: сжаты семь ячеек таблицы модулей и три
    // абзаца раздела CI, пересказывавшие свой же разбор (−1.3 КБ). Прибавка
    // (+1.9 КБ) — ПЯТЬ правил в Gotchas со ссылками (плита принадлежит
    // таймеру, таймер — восьмой подвижный элемент, подпись плашки, шрифт
    // переменной, Esc не гасит окна) и ПЯТЬ строк в таблицах тестов; сами
    // разборы (13 КБ) ушли в docs/lessons.md.
    //
    // 28.08.2026, первая правка дня: порог НЕ поднят — сжат 21 пересказ в
    // таблицах e2e-спек и модулей (−830 Б), добавлены ДВА правила в Gotchas
    // (поле payload без чтения; две одинаковые кнопки рядом).
    //
    // 28.08.2026, вторая: поднят с 57600 до 59100, и цена записана. Сжатие
    // пробовалось первым и НЕ ДАЛО: раздел «Security» набран по-английски и
    // короче любого русского пересказа — переписанный, он вырос на 380 Б и был
    // возвращён как был. Прибавка (+1.4 КБ) — ПЯТЬ строк в таблицах тестов
    // (`money-meter`, `floor-47` и `display-proportions` отсутствовали там
    // вовсе, причём первые два — с 26.08.2026) и ОДНО правило со ссылкой (место
    // — доля, значит и размер доля). Это реестр и императив, то есть ровно то,
    // что здесь и должно жить; сам разбор (4 КБ) ушёл в docs/lessons.md.
    //
    // Следующая правка снова начинает со сжатия. Кандидат один и он честный:
    // Gotchas разросся до 27 КБ, и в нём около тридцати строк вида
    // «- **Sounds** — [разбор]» — это не императив, а оглавление чужого файла.
    // Свести их в один абзац со ссылками — минус примерно 1.5 КБ.
    const bytes = Buffer.byteLength(claude, 'utf8');
    assert.ok(
        bytes < 59100,
        `CLAUDE.md разросся до ${bytes} байт — хроника снова переезжает в правила? Разбор пишется в docs/lessons.md`
    );
});

test('в CLAUDE.md не осталось развёрнутой хроники вместо правил', () => {
    // Признак хроники — многострочный пункт: правило умещается в строку, а
    // история требует абзаца. Разрешаем шапку раздела, но не пункты списка.
    const section = claude.slice(claude.indexOf('## Gotchas'), claude.indexOf('## Automation'));
    const bullets = section.split('\n').filter((l) => l.startsWith('- '));
    assert.ok(bullets.length > 50, `пунктов подозрительно мало (${bullets.length}) — раздел не потерялся?`);

    const tooLong = bullets.filter((l) => l.length > 400).map((l) => l.slice(0, 70));
    assert.deepStrictEqual(
        tooLong, [],
        `в правила вернулась хроника — эти пункты длиннее 400 символов:\n${tooLong.join('\n')}`
    );
});
