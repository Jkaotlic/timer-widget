'use strict';

/**
 * Размеры подвижных карточек дисплея ведутся от ПОЛОСЫ СОДЕРЖИМОГО.
 *
 * Жалоба 28.08.2026: «раскладка ведёт себя по-разному на разных дисплеях».
 * Причина была не в раскладке: место элемента хранилось долей окна, а размер —
 * пикселями с ПОТОЛКОМ (`clamp(13px, 1.4vmin, 18px)`). Карточка занимала 14,1 %
 * полосы на 3380×1253 и 30,4 % на 1366×1024; раз она шире — её край упирается в
 * поле у границы, и поджатие толкает её внутрь, отчего разъезжались и центры.
 *
 * Замер живёт в e2e (display-proportions.spec.js), но там он ВЫНУЖДЕННО
 * снимается на маленьком экране: чтобы дефект проявился, полосы двух окон
 * должны различаться в полтора раза, а на раннере CI (1024×720) оба конца
 * лежат на пороге читаемости. Поэтому сам механизм закреплён здесь — эта
 * проверка идёт везде.
 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const CSS = fs.readFileSync(path.join(__dirname, '..', 'display.css'), 'utf8');

/** Тело правила по селектору — первое вхождение, без вложенности. */
function rule(selector) {
    const at = CSS.indexOf(`\n${selector} {`);
    assert.ok(at > 0, `правило ${selector} не найдено`);
    return CSS.slice(at, CSS.indexOf('\n}', at));
}

test('мера окна объявлена в КОРНЕ, а не в контейнере таймера', () => {
    // Первая версия положила её в `.display-container` и не сработала совсем:
    // подвижные карточки лежат в разметке РЯДОМ с ним, наследование до них не
    // доходит, `var(--band-unit)` не разрешался, и браузер выбрасывал всё
    // объявление целиком. Симптом был не «размер другой», а «стиля нет»:
    // кегль 16px и нулевые поля, то есть вид без CSS вообще.
    const root = rule(':root');
    assert.match(root, /--content-band:\s*min\(100vw,\s*177\.78vh\)/,
        'полоса содержимого не объявлена в :root');
    assert.match(root, /--band-unit:\s*calc\(var\(--content-band\)\s*\/\s*100\)/,
        'единица полосы не объявлена в :root');

    // Само-проверка зонда: он обязан НАХОДИТЬ переменную, которая объявлена в
    // другом правиле, — иначе зелёный выше значил бы «смотрю не туда».
    assert.ok(!/--timer-box/.test(root),
        'зонд захватил чужое правило — срез :root шире, чем должен быть');
    assert.match(rule('.display-container'), /--timer-box/,
        'зонд не видит правила .display-container — регулярка не работает');
});

test('кегли карточки — доля полосы, и ПОТОЛКА у них нет', () => {
    // Потолок и есть та поломка: он останавливал рост карточки там, где таймер
    // продолжал расти вместе с экраном.
    for (const selector of ['.info-label', '.info-value']) {
        const body = rule(selector);
        const m = /font-size:\s*([^;]+);/.exec(body);
        assert.ok(m, `${selector}: нет кегля`);
        const size = m[1];
        assert.ok(size.includes('var(--band-unit)'),
            `${selector}: кегль не ведётся от полосы содержимого — ${size}`);
        assert.ok(!size.includes('clamp('),
            `${selector}: кегль снова в clamp() — у clamp есть верхняя граница, а её быть не должно: ${size}`);
        assert.match(size, /^max\(/,
            `${selector}: нижний порог читаемости обязан остаться — ${size}`);
    }
});

test('таймер НАМЕРЕННО остался на высоте окна', () => {
    // Он квадратный и обязан влезать по вертикали. Доля полосы попросила бы у
    // него 98 % высоты на сверхшироком экране — это не забытый случай, а
    // решение, и оно записано.
    const container = rule('.display-container');
    assert.match(container, /--timer-box:[^;]*55vh/,
        'таймер увели с высоты окна — на сверхшироком экране он перестанет помещаться');
    assert.ok(/ВЫСОТЕ|высоте/.test(CSS.slice(CSS.indexOf('--content-band') - 1200, CSS.indexOf('--content-band'))),
        'решение про таймер не объяснено рядом с мерой — следующий сведёт их к одному закону');
});
